// ===== THEME MANAGER (DARK MODE) =====
let currentTheme = localStorage.getItem('tofistiki_theme');

// Match system preference if no saved theme
if (!currentTheme) {
    if (window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches) {
        currentTheme = 'dark';
    } else {
        currentTheme = 'light';
    }
}

function setTheme(theme) {
    currentTheme = theme;
    localStorage.setItem('tofistiki_theme', theme);
    document.documentElement.setAttribute('data-theme', theme);

    // Update toggle icon
    const themeIcon = document.querySelector('.theme-icon');
    if (themeIcon) {
        themeIcon.textContent = theme === 'dark' ? '☀️' : '🌙';
    }
}

// ===== LANGUAGE MANAGER =====
let currentLang = localStorage.getItem('tofistiki_lang') || 'el';

function setLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('tofistiki_lang', lang);
    document.documentElement.lang = lang;

    // Update all translatable elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[lang] && translations[lang][key]) {
            el.innerHTML = translations[lang][key];
        }
    });

    // Update toggle button
    const toggle = document.getElementById('lang-toggle');
    if (toggle) {
        const flag = toggle.querySelector('.lang-flag');
        const label = toggle.querySelector('.lang-label');
        if (lang === 'el') {
            flag.textContent = '🇬🇧';
            label.textContent = 'EN';
        } else {
            flag.textContent = '🇬🇷';
            label.textContent = 'ΕΛ';
        }
    }

    // Update page title
    document.title = lang === 'el'
        ? 'Το Φυστίκι — Κάβα Ποτών & Ξηρών Καρπών'
        : 'To Fistiki — Drinks & Nuts Cellar';
}

// ===== EVENT LISTENERS =====
document.getElementById('lang-toggle')?.addEventListener('click', () => {
    setLanguage(currentLang === 'el' ? 'en' : 'el');
});

document.getElementById('theme-toggle')?.addEventListener('click', () => {
    setTheme(currentTheme === 'light' ? 'dark' : 'light');
});

// Watch for system theme changes
window.matchMedia('(prefers-color-scheme: dark)').addEventListener('change', e => {
    if (!localStorage.getItem('tofistiki_theme')) {
        setTheme(e.matches ? 'dark' : 'light');
    }
});

// ===== SMOOTH SCROLLING =====
document.querySelectorAll('a[href^="#"]').forEach(anchor => {
    anchor.addEventListener('click', function (e) {
        e.preventDefault();
        const target = document.querySelector(this.getAttribute('href'));
        if (target) {
            target.scrollIntoView({ behavior: 'smooth', block: 'start' });
            // Update active nav link
            document.querySelectorAll('.nav-link').forEach(l => l.classList.remove('active'));
            if (this.classList.contains('nav-link')) {
                this.classList.add('active');
            }
            // Close mobile menu
            navMenu?.classList.remove('active');
            hamburger?.classList.remove('active');
        }
    });
});

// ===== ACTIVE NAV ON SCROLL =====
const sections = document.querySelectorAll('section[id]');
const navLinks = document.querySelectorAll('.nav-link');

function updateActiveNav() {
    const scrollY = window.scrollY;

    sections.forEach(section => {
        const top = section.offsetTop - 120;
        const height = section.clientHeight;
        const id = section.getAttribute('id');

        if (scrollY >= top && scrollY < top + height) {
            navLinks.forEach(link => {
                link.classList.remove('active');
                if (link.getAttribute('href') === `#${id}`) {
                    link.classList.add('active');
                }
            });
        }
    });
}

// ===== NAVBAR SCROLL EFFECT =====
const navbar = document.getElementById('navbar');

function handleNavScroll() {
    if (window.scrollY > 60) {
        navbar.classList.add('scrolled');
    } else {
        navbar.classList.remove('scrolled');
    }
}

// ===== SCROLL TO TOP =====
const scrollTopBtn = document.getElementById('scroll-top');

function handleScrollTop() {
    if (window.scrollY > 500) {
        scrollTopBtn?.classList.add('visible');
    } else {
        scrollTopBtn?.classList.remove('visible');
    }
}

scrollTopBtn?.addEventListener('click', () => {
    window.scrollTo({ top: 0, behavior: 'smooth' });
});

// Combined scroll handler
window.addEventListener('scroll', () => {
    updateActiveNav();
    handleNavScroll();
    handleScrollTop();
}, { passive: true });

// ===== HAMBURGER MENU =====
const hamburger = document.getElementById('hamburger');
const navMenu = document.getElementById('nav-menu');

hamburger?.addEventListener('click', () => {
    navMenu.classList.toggle('active');
    hamburger.classList.toggle('active');
    hamburger.setAttribute('aria-expanded', navMenu.classList.contains('active') ? 'true' : 'false');
});

