// ===== MOUSE CURSOR GLOW ON HERO =====
const heroSection = document.querySelector('.hero');
const heroCursor = document.getElementById('hero-cursor');

if (heroSection && heroCursor) {
    heroSection.addEventListener('mousemove', (e) => {
        const rect = heroSection.getBoundingClientRect();
        const x = e.clientX - rect.left;
        const y = e.clientY - rect.top;

        // Use requestAnimationFrame for smooth performance
        requestAnimationFrame(() => {
            heroCursor.style.left = `${x}px`;
            heroCursor.style.top = `${y}px`;
        });
    });
}

// ===== PARALLAX ON HERO =====
let ticking = false;
window.addEventListener('scroll', () => {
    if (!ticking) {
        requestAnimationFrame(() => {
            const heroContent = document.querySelector('.hero-content');
            if (heroContent && window.scrollY < window.innerHeight) {
                const offset = window.scrollY * 0.3;
                heroContent.style.transform = `translateY(${offset}px)`;
                heroContent.style.opacity = 1 - (window.scrollY / window.innerHeight) * 0.6;
            }
            ticking = false;
        });
        ticking = true;
    }
}, { passive: true });

